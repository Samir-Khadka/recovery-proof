"""Dashboard (Recovery Proof v0.4, Phase 3).

``recovery-proof dashboard`` reads the restore history and the audit
history and writes one self-contained HTML page — no server, no JavaScript
framework, no external assets — that a team can open in a browser or host
as a static file. Each system gets a card with its readiness score and
grade, the measured recovery time, the pass rate, the last run, and the
latest protection audit.

The palette follows Samir's rule for his sites: light premium (warm ivory
background, royal violet accent, antique gold highlights) — never a black
background.
"""
from __future__ import annotations

import argparse
import html
import logging
import sys
from pathlib import Path

from .history import default_audit_results_path, default_results_path, load_history
from .score import grade_for, load_systems_config, score_systems

log = logging.getLogger("recovery-proof.dashboard")

EXIT_PASS = 0
EXIT_INFRA = 2

GRADE_COLOURS = {
    "A": "#1e7d46", "B": "#2e6fb7", "C": "#8a6d00",
    "D": "#b3541e", "F": "#b3261e",
}


def _grade_badge(grade: str) -> str:
    colour = GRADE_COLOURS.get(grade, "#666")
    return (f'<span style="display:inline-block;min-width:2.2em;text-align:center;'
            f'background:{colour};color:#fff;font-weight:700;border-radius:6px;'
            f'padding:0.15em 0.4em;">{html.escape(grade)}</span>')


def _bar(earned: float, weight: int) -> str:
    pct = max(0.0, min(100.0, 100 * earned / weight)) if weight else 0
    return (f'<span style="display:inline-block;width:120px;height:8px;'
            f'background:#e8e2d4;border-radius:4px;overflow:hidden;'
            f'vertical-align:middle;"><span style="display:block;height:100%;'
            f'width:{pct:.0f}%;background:#5b3ea8;"></span></span>')


def build_dashboard(results: list[dict], audits: list[dict],
                    systems: dict, rto_seconds: float | None) -> str:
    """Render the dashboard HTML from the loaded histories."""
    scored = score_systems(results, audits, systems, rto_seconds)
    worst = min((s["grade"] for s in scored), default="—",
                key=lambda g: "FDCBA".index(g) if g in "FDCBA" else 99)
    cards = []
    for s in scored:
        rows = []
        for c in s["components"]:
            status = "no data" if c["status"] == "no data" else f"{c['earned']:.0f}/{c['weight']}"
            rows.append(
                f"<tr><td>{html.escape(c['name'])}</td>"
                f"<td>{_bar(c['earned'], c['weight'])} {status}</td>"
                f"<td>{html.escape(c['detail'])}</td></tr>")
        measured = s["measured"]
        cards.append(f"""
    <section style="background:#fffdf7;border:1px solid #e8e2d4;border-radius:12px;
                    padding:1.2em 1.4em;margin-bottom:1.2em;">
      <h2 style="margin:0 0 0.2em;">{html.escape(s['system'])}
        {_grade_badge(s['grade'])}
        <span style="font-size:1.4em;font-weight:700;color:#3a2a6b;">{s['score']}/100</span></h2>
      <p style="margin:0.2em 0 0.8em;color:#555;">
        Measured median restore: <strong>{measured['median_duration_s']}s</strong>
        over {measured['runs']} runs
        {f"· declared RTO {measured['declared_rto_s']:.0f}s" if measured['declared_rto_s'] is not None else "· no declared RTO"}
      </p>
      <table style="border-collapse:collapse;width:100%;font-size:0.95em;">
        <thead><tr style="text-align:left;color:#777;">
          <th>Component</th><th>Score</th><th>Evidence (measured)</th></tr></thead>
        <tbody>{''.join(rows)}</tbody>
      </table>
    </section>""")
    body = "\n".join(cards) if cards else (
        "<p>No restore runs recorded yet. Run a check first — "
        "<code>recovery-proof check --backup-file … --checks …</code> — "
        "and the dashboard will fill in.</p>")
    return f"""<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8">
<title>Recovery Proof — dashboard</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
  body {{ font-family: system-ui, -apple-system, sans-serif; background:#faf6ec;
          color:#222; margin:0; padding:2em 1.5em; }}
  main {{ max-width: 860px; margin: 0 auto; }}
  h1 {{ color:#3a2a6b; margin-bottom:0.1em; }}
  .sub {{ color:#666; margin-top:0; }}
  code {{ background:#efe9d8; padding:0.1em 0.3em; border-radius:4px; }}
  td, th {{ padding:0.35em 0.6em 0.35em 0; vertical-align:top; }}
</style></head>
<body><main>
  <h1>Recovery Proof — dashboard</h1>
  <p class="sub">{len(scored)} system(s) · worst grade {html.escape(worst)} ·
  every number below is a measured fact from the restore history and the
  latest protection audit.</p>
  {body}
  <p class="sub">Generated by Recovery Proof. A component with no data scores
  0 and says so — the score is only as good as the evidence behind it.</p>
</main></body>
</html>
"""


def parse_dashboard_args(argv=None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="Recovery Proof dashboard (static HTML)")
    ap.add_argument("--output", type=Path, default=Path("dashboard.html"),
                    help="where to write the page (default: ./dashboard.html)")
    ap.add_argument("--results", type=Path, default=default_results_path())
    ap.add_argument("--audit-results", type=Path, default=default_audit_results_path())
    ap.add_argument("--systems", type=Path,
                    help="systems config file: {label: {rto_seconds: N}} (YAML or JSON)")
    ap.add_argument("--rto-seconds", type=float,
                    help="declared RTO in seconds (applies to all systems)")
    ap.add_argument("-v", "--verbose", action="store_true")
    return ap.parse_args(argv)


def dashboard_main(argv=None) -> int:
    args = parse_dashboard_args(argv)
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(levelname)s %(message)s")
    systems = {}
    if args.systems:
        try:
            systems = load_systems_config(args.systems)
        except (ValueError, FileNotFoundError, KeyError) as e:
            log.error("systems config error: %s", e)
            return EXIT_INFRA
    results = load_history(args.results)
    audits = load_history(args.audit_results)
    page = build_dashboard(results, audits, systems, args.rto_seconds)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(page, encoding="utf-8")
    log.info("dashboard written to %s (%d system(s))",
             args.output, len(score_systems(results, audits, systems, args.rto_seconds)))
    return EXIT_PASS


if __name__ == "__main__":
    sys.exit(dashboard_main())
